export function formatPrice(priceUsd: number, lang: Language): { main: string; sub?: string; period: string } {
  const usdFormatted = new Intl.NumberFormat('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: 0,
  }).format(priceUsd);

  if (lang === 'vi') {
    const vndMillion = (priceUsd * 25400) / 1_000_000;
    const formattedMillion =
      vndMillion >= 100
        ? Math.round(vndMillion).toLocaleString('vi-VN')
        : (vndMillion % 1 === 0 ? vndMillion.toFixed(0) : vndMillion.toFixed(1));
    return {
      main: `${usdFormatted} / tháng`,
      sub: `~${formattedMillion} Triệu / tháng`,
      period: '/ tháng',
    };
  }

  return {
    main: `${usdFormatted} / month`,
    sub: undefined,
    period: '/ month',
  };
}
